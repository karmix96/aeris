def progression(n: int, ratio: float, *, both_ends: bool = False) -> Array:
    """Normalised geometric point distribution, paper §1.1.2 eq 1.1-1.3.

    ``both_ends`` gives the two-directional progression §3.1.4 asks for on the long
    chord curves: dense at the aerodynamically interesting end, coarse toward
    mid-chord.
    """
    if n < 2:
        raise MeshBuildError("progression needs at least 2 points.")
    if abs(ratio - 1.0) < 1e-12:
        return np.linspace(0.0, 1.0, n)
    if both_ends:
        s = progression(n, ratio, both_ends=False)
        return 0.5 * (s + (1.0 - s[::-1]))
    steps = ratio ** np.arange(n - 1)
    cum = np.concatenate([[0.0], np.cumsum(steps)])
    return cum / cum[-1]


def _resample_at(curve: Array, t: Array) -> Array:
    """Resample a polyline at normalised arc-length positions ``t``."""
    seg = np.linalg.norm(np.diff(curve, axis=0), axis=1)
    cum = np.concatenate([[0.0], np.cumsum(seg)])
    total = cum[-1] or 1.0
    tt = t * total
    return np.column_stack([np.interp(tt, cum, curve[:, i]) for i in range(curve.shape[1])])


