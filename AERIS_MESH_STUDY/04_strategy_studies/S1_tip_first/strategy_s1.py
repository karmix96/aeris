OML_NAMES = [f"oml_{k}" for k in ARC_ORDER]


def _resample_oml_spanwise(blocks: list[SurfaceBlock], span_cells: int) -> list[SurfaceBlock]:
    """Resample only OML columns while preserving every tip-cap block exactly."""
    if span_cells < 2:
        raise MeshBuildError("span_cells must be at least two")
    out: list[SurfaceBlock] = []
    for block in blocks:
        if not block.name.startswith("oml_") or block.xyz.shape[1] == span_cells + 1:
            out.append(block)
            continue
        old_t = np.linspace(0.0, 1.0, block.xyz.shape[1])
        new_t = np.linspace(0.0, 1.0, span_cells + 1)
        xyz = np.stack(
            [np.column_stack([np.interp(new_t, old_t, block.xyz[i, :, axis]) for axis in range(3)])
             for i in range(block.xyz.shape[0])],
            axis=0,
        )
        out.append(SurfaceBlock(name=block.name, xyz=xyz, family=block.family))
    return out


def build_surface(
    wing,
    *,
    level: str = "L2_smoke",
    te_thickness_abs_m: float = TE_THICKNESS_ABS_M,
    ratio: float = 1.0,
    end_scale: float = 5.0,
    tip_anchored_spanwise: bool = True,
    spanwise_first_cell_factor: float = 0.12,
    growth_limit: float = GROWTH_LIMIT,
    realise_law: bool = True,
    span_cells: int | None = None,
    **overrides,
) -> tuple[list[SurfaceBlock], dict]:
    """Build S1: 6 OML blocks swept tip-to-root plus the 7-domain tip."""
    if level not in LEVELS:
        raise MeshBuildError(f"unknown level {level!r}; known: {sorted(LEVELS)}")
    cfg = dict(LEVELS[level])
    cfg.update({k: v for k, v in overrides.items() if v is not None})

    xsecs = list(wing.xsecs)
    if len(xsecs) < 3:
        raise MeshBuildError("S1 needs at least three spanwise stations.")

    sides_by_xsec, tip_geom = [], None
    for xsec in xsecs:
        coords, le_index = section_loop_2d(xsec, te_thickness_abs_m=te_thickness_abs_m)
        g = section_geometry(
            coords, le_index,
            chord_points=cfg["chord_points"], end_points=cfg["end_points"], ratio=ratio,
            end_scale=end_scale,
        )
        tip_geom = g
        sides_by_xsec.append([g["outer"][k] for k in ARC_ORDER])

    oml = _map_sides_to_wing(wing, sides_by_xsec)

    le_line = np.asarray(
        wing.mesh_line(x_nondim=[0.0] * len(xsecs), z_nondim=[0.0] * len(xsecs), add_camber=False)
    )
    lengths = [float(np.linalg.norm(le_line[i + 1] - le_line[i])) for i in range(len(xsecs) - 1)]
    if tip_anchored_spanwise:
        # First spanwise cell matched to the tip cap's own radial cell (§3.1.5).
        cap_probe, _ = tip_domains_2d(tip_geom, collar_points=cfg["collar_points"])
        radial = []
        for patch in cap_probe[:-1]:
            d = np.linalg.norm(np.diff(patch, axis=1), axis=2)
            radial.append(float(np.median(d)))
        first_cell = float(np.median(radial)) * spanwise_first_cell_factor
        counts = spanwise_counts_tip_anchored(
            lengths, first_cell=first_cell, growth=growth_limit,
            max_cell=cfg["target_cell_m"],
        )
    else:
        counts = [
            np.linspace(0.0, 1.0, n + 1)[:-1]
            for n in spanwise_counts(
                lengths, target_cell=cfg["target_cell_m"], growth_limit=growth_limit
            )
        ]
    if realise_law:
        oml = sweep_tip_to_root(oml, counts)

    blocks = [SurfaceBlock(name=n, xyz=b, family="wall") for n, b in zip(OML_NAMES, oml, strict=True)]

    native_span_cells = int(sum(len(np.atleast_1d(c)) for c in counts))
    if span_cells is not None and int(span_cells) != native_span_cells:
        blocks = _resample_oml_spanwise(blocks, int(span_cells))

    cap_2d, cap_info = tip_domains_2d(tip_geom, collar_points=cfg["collar_points"])
    blocks += [
        SurfaceBlock(name=n, xyz=map_patch_2d_to_tip(wing, p), family="wall")
        for n, p in zip(cap_info["block_names"], cap_2d, strict=True)
    ]

    blocks, orientation = orient_blocks_consistently(blocks)
    info = {
        "strategy_id": STRATEGY_ID,
        "level": level,
        "level_settings": cfg,
        "te_thickness_abs_m": te_thickness_abs_m,
        "progression_ratio": ratio,
        "end_scale": end_scale,
        "sweep_direction": "tip_to_root",
        "oml_block_names": OML_NAMES,
        "tip_block_names": cap_info["block_names"],
        "tip_closure": cap_info["topology"],
        "tip_cap_info": cap_info,
        "orientation": orientation,
        "spanwise": {
            "target_cell_m": cfg["target_cell_m"],
            "growth_limit": growth_limit,
            "segment_lengths_m": lengths,
            "cells_per_interval": [int(len(np.atleast_1d(c))) for c in counts],
            "realised": bool(realise_law),
            "spanwise_cells": int(span_cells) if span_cells is not None else native_span_cells,
            "requested_span_cells": int(span_cells) if span_cells is not None else None,
            "realized_span_cells": int(span_cells) if span_cells is not None else native_span_cells,
            "native_stations": len(xsecs),
        },
        "source": "Openblademesh (Heider 2023) §3.1.4, followed faithfully",
    }
    return blocks, info
