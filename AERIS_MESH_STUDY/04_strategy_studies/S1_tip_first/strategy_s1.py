def spanwise_counts(
    lengths: list[float], *, target_cell: float, growth_limit: float = GROWTH_LIMIT,
    minimum: int = 2,
) -> list[int]:
    """Cells per spanwise interval, growth-limited.

    The paper's implemented rule is eq 3.11 (a negative exponential), which it calls
    "coarser" and "not sufficient". Equations 3.5-3.10 give the intended single
    geometric series and are explicitly **not used** in the source. What is added
    here is the growth limit §4.2.3 names (1.3-1.6) and says Openblademesh cannot
    enforce — the direct answer to the §3.1.7 failure where pyHyp refuses the whole
    wing because tip-to-wing step size differs too much.
    """
    raw = [max(minimum, int(round(length / max(target_cell, 1e-12)))) for length in lengths]
    for _ in range(len(raw) * 4):
        changed = False
        for i in range(len(raw) - 1):
            hi, lo = max(raw[i], raw[i + 1]), min(raw[i], raw[i + 1])
            if hi > lo * growth_limit:
                capped = max(minimum, int(np.ceil(lo * growth_limit)))
                if raw[i] > raw[i + 1]:
                    raw[i] = capped
                else:
                    raw[i + 1] = capped
                changed = True
        if not changed:
            break
    return raw


def spanwise_counts_tip_anchored(
    lengths: list[float],
    *,
    first_cell: float,
    growth: float,
    max_cell: float,
    minimum: int = 1,
) -> list[int]:
    """Equations 3.5-3.10: ONE geometric series over the whole wing, anchored at the tip.

    This is the law Openblademesh gives in full and then states it does not use —
    "the algebraic solution approach takes too long and the numerical approach is yet
    to be finished so the formula is given here but is not used" (§3.1.5) — and whose
    absence is the reason it reports "Pyhyp cannot extrude the whole wing for too big
    step size differences between the wingtip and the wing" (§3.1.7).

    §3.1.5 states the requirement plainly: "it is important to generate cells on the
    wing towards the wingtip which are as similar as possible to the cells on the
    wingtip on the edge. Because the wingtip will have very small cells, especially
    at the Trailing Edge, the cells on the wing need to be very small. However, if
    this cell dimension would be consistent over the whole wing the computational
    load would be enormous."

    So: start at the tip with ``first_cell`` — the tip cap's own radial cell size —
    and grow inboard by ``growth`` per cell (§4.2.3 bounds this at 1.3-1.6) until
    ``max_cell``. Solved by walking rather than algebraically, which is what the
    source found too slow.

    ``lengths`` is ordered root -> tip, so the walk consumes it in reverse.

    ``spanwise_first_cell_factor`` scales the tip cap's median radial cell to set the
    first spanwise cell. Measured against the tip/OML size jump, which is what
    section 3.1.5 asks to close:

        factor 0.50  ->  outboard cell 2186 um,  jump 3.86
        factor 0.25  ->                1165 um,  jump 2.06
        factor 0.12  ->                 558 um,  jump 0.99   <- default
        factor 0.06  ->                 272 um,  jump 0.48

    0.12 lands the outboard spanwise cell on the tip cap's own radial cell size.
    The factor is below 1 because the probe takes the MEDIAN radial cell over the
    cap's collars while the jump that matters is against the smallest of them.

    **Why it matters, measured.** Without it the outboard spanwise cells were
    14-21 mm against tip-cap radial cells of 0.13-1.0 mm — a 28:1 jump straight
    across the tip interface — and pyHyp produced a negative volume in layer 2 and
    diverged, twice, at both `end_scale` 1.0 and 5.0.
    """
    out: list[Array] = []
    size = float(first_cell)
    for length in reversed(lengths):
        length = float(length)
        # Walk outboard-to-inboard laying down cells of the running size. The
        # positions, not just the count, must follow the series: placing n cells
        # UNIFORMLY inside the interval throws the progression away and leaves the
        # outboard cell as large as before. That was measured — the tip/OML size
        # jump stayed at 33.8 until the positions were carried through.
        edges, acc, n = [0.0], 0.0, 0
        while acc + size < length and n < 100000:
            acc += size
            edges.append(acc)
            n += 1
            size = min(size * growth, max_cell)
        if len(edges) < minimum + 1:
            edges = list(np.linspace(0.0, length, minimum + 1))[:-1]
            acc = edges[-1]
        # Fractions measured from the OUTBOARD end, flipped into the interval's own
        # root->tip parameterisation. `edges[0] == 0` is the OUTBOARD end, i.e.
        # fraction 1.0 — that is the NEXT station's own column, so it must be
        # dropped or every interval boundary gets a duplicated, zero-length
        # spanwise edge (measured: min scaled Jacobian 0.0, cell-size range inf).
        # Rescale so the series fills the interval EXACTLY. Folding the leftover
        # into the final cell instead lets that cell exceed `max_cell` — measured,
        # the root interval's last cell reached 26.8 mm against a 15 mm cap and the
        # cell-size range went UP, 172.7 -> 214.8. Rescaling preserves the shape of
        # the progression and respects the cap.
        e = np.asarray(edges, dtype=float)
        e = e / (e[-1] or 1.0)
        frac = 1.0 - e[1:]
        frac = np.concatenate([[0.0], frac[frac > 1e-9]])
        out.append(np.unique(frac))
    return list(reversed(out))


def sweep_tip_to_root(blocks: list[Array], fractions_per_interval) -> list[Array]:
    """Subdivide each spanwise interval at the given fractions, tip-first (§3.1.5).

    ``fractions_per_interval[j]`` holds the normalised positions inside interval j,
    starting at 0.0 and excluding 1.0 (which is the next station's own column).
    Accepting positions rather than counts is what lets the global geometric series
    of eq 3.5-3.10 actually reach the mesh.
    """
    n_int = blocks[0].shape[1] - 1
    if len(fractions_per_interval) != n_int:
        raise MeshBuildError(f"law gives {len(fractions_per_interval)}, blocks have {n_int}")
    out = []
    for blk in blocks:
        cols = []
        for j, fracs in enumerate(fractions_per_interval):
            for s in np.atleast_1d(fracs):
                cols.append((1.0 - s) * blk[:, j, :] + s * blk[:, j + 1, :])
        cols.append(blk[:, -1, :])
        out.append(np.stack(cols, axis=1))
    return out


def map_patch_2d_to_tip(wing, patch_2d: Array) -> Array:
    n_xsec = len(wing.xsecs)
    sides = [[patch_2d[i] for i in range(patch_2d.shape[0])] for _ in range(n_xsec)]
    return np.stack([m[:, -1, :] for m in _map_sides_to_wing(wing, sides)], axis=0)


