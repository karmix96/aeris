# §3.1.4 the subsection and the tip domains
# ---------------------------------------------------------------------------


def section_geometry(
    coords: Array,
    le_index: int,
    *,
    chord_points: int,
    end_points: int,
    ratio: float,
    end_scale: float = 1.0,
) -> dict:
    """The six outer arcs and four inner arcs of one section.

    Outer, in ring order from the upper trailing edge:

        upper_aft   upper TE corner -> mid-chord
        upper_fore  mid-chord       -> nose station
        nose        upper nose      -> around LE -> lower nose
        lower_fore  nose station    -> mid-chord
        lower_aft   mid-chord       -> lower TE corner
        base        lower TE corner -> upper TE corner   (the blunt trailing edge)
    """
    upper, lower = _surfaces(coords, le_index)
    x_le, x_te = float(upper[0, 0]), float(upper[-1, 0])
    x_nose, x_aft = end_stations(coords, le_index, end_scale=end_scale)
    x_mid = 0.5 * (x_le + x_te)

    def _arc(curve: Array, xa: float, xb: float, n: int) -> Array:
        lo, hi = min(xa, xb), max(xa, xb)
        mask = (curve[:, 0] > lo) & (curve[:, 0] < hi)
        mid = curve[mask]
        if xb < xa:
            mid = mid[::-1]
        seg = np.vstack([_point_on(curve, xa), mid, _point_on(curve, xb)])
        # Dense toward the aerodynamically interesting end (§3.1.4): the aft
        # halves cluster at the trailing edge, the fore halves at the nose.
        return _resample_at(seg, progression(n, ratio))

    # Paper code line 408: `Inter_X[3] = 0.5 * Inter_X[2]`. The OUTER nose split
    # sits at HALF the inner nose station — i.e. FORWARD of it, nearer the leading
    # edge — so the connection line runs aft-and-inward at roughly 45 degrees.
    #
    # Both other readings were tried and are worse:
    #   * outer split at the inner station  -> connection line vertical, collinear
    #     with a near-vertical contour: `tip_nose` skew 1.000, jac -0.000
    #   * outer split solved AFT for |dx|==|dz| -> line points forward against the
    #     inner edge: jac -0.816 to -0.902
    # Reading the listing rather than inferring the rule is what settled it.
    x_no_up = x_le + 0.5 * (x_nose - x_le)
    x_no_lo = x_no_up
    nose_up = upper[(upper[:, 0] <= x_no_up)]
    nose_lo = lower[(lower[:, 0] <= x_no_lo)]
    o_nose = np.vstack([
        _point_on(upper, x_no_up), nose_up[::-1], nose_lo[1:], _point_on(lower, x_no_lo),
    ])

    outer = {
        "upper_aft": _arc(upper, x_te, x_mid, chord_points),
        "upper_fore": _arc(upper, x_mid, x_no_up, chord_points),
        "nose": _resample_at(o_nose, np.linspace(0.0, 1.0, end_points)),
        "lower_fore": _arc(lower, x_no_lo, x_mid, chord_points),
        "lower_aft": _arc(lower, x_mid, x_te, chord_points),
        "base": _straight(lower[-1], upper[-1], end_points),
    }

    def _inner(xa: float, xb: float, n: int, up: bool) -> Array:
        xq = xa + (xb - xa) * progression(n, ratio)
        iu, il = inner_airfoil(coords, le_index, xq, dilation=X_DILATION)
        return np.column_stack([xq, iu if up else il])

    iu_n, il_n = inner_airfoil(coords, le_index, np.array([x_nose]), dilation=X_DILATION)
    iu_a, il_a = inner_airfoil(coords, le_index, np.array([x_aft]), dilation=X_DILATION)
    inner = {
        "upper_aft": _inner(x_aft, x_mid, chord_points, True),
        "upper_fore": _inner(x_mid, x_nose, chord_points, True),
        "nose": _straight(np.array([x_nose, iu_n[0]]), np.array([x_nose, il_n[0]]), end_points),
        "lower_fore": _inner(x_nose, x_mid, chord_points, False),
        "lower_aft": _inner(x_mid, x_aft, chord_points, False),
        "base": _straight(np.array([x_aft, il_a[0]]), np.array([x_aft, iu_a[0]]), end_points),
    }
    return {
        "outer": outer, "inner": inner,
        "x_le": x_le, "x_te": x_te, "x_nose": x_nose, "x_aft": x_aft, "x_mid": x_mid,
    }


ARC_ORDER = ("upper_aft", "upper_fore", "nose", "lower_fore", "lower_aft", "base")


def tip_domains_2d(geom: dict, *, collar_points: int) -> tuple[list[Array], dict]:
    """The paper's seven wingtip domains, all four-cornered (§3.1.4)."""
    outer, inner = geom["outer"], geom["inner"]
    patches, names = [], []
    for key in ARC_ORDER:
        o, i = outer[key], inner[key]
        if len(o) != len(i):
            raise MeshBuildError(f"{key}: outer {len(o)} vs inner {len(i)} points")
        patches.append(
            _tfi_patch(
                bottom=o, top=i,
                left=_straight(o[0], i[0], collar_points),
                right=_straight(o[-1], i[-1], collar_points),
            )
        )
        names.append(f"tip_{key}")

    # The centre, bounded by the four long inner arcs and the two short end edges.
    inner_low = np.vstack([inner["lower_fore"], inner["lower_aft"][1:]])   # nose -> aft
    inner_up = np.vstack([inner["upper_fore"][::-1], inner["upper_aft"][::-1][1:]])
    patches.append(
        _tfi_patch(
            bottom=inner_low, top=inner_up,
            left=inner["nose"][::-1], right=inner["base"],
        )
    )
    names.append("tip_centre")

    patches, flipped = orient_patches_2d(patches)
    info = {
        "topology": "openblademesh_inner_airfoil_seven_domain",
        "block_names": names,
        "dilation_X": X_DILATION,
        "nose_end_frac_of_chord": float((geom["x_nose"] - geom["x_le"]) / (geom["x_te"] - geom["x_le"])),
        "te_end_frac_of_chord": float((geom["x_te"] - geom["x_aft"]) / (geom["x_te"] - geom["x_le"])),
        "collar_points": int(collar_points),
        "orientation_flipped": flipped,
        "source": "Openblademesh §3.1.4: X=0.33, sqrt(2)*0.003 nose, TE/4 aft, mid-chord split",
    }
    return patches, info


