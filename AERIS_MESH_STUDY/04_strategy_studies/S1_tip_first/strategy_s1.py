"""S1 — tip-first sweep, following Openblademesh faithfully.

Source: Michael A. Heider, *Create an Automated Structured Mesh Generation Method
for Rotor Blades using Exclusively Open Source Software*, Bachelor Thesis, IAG
Universität Stuttgart, September 2023 —
`papers/Openblademesh_Bachelor_Thesis_Michael_Heider_Abgabe_noBK.pdf`.
Read in full; the construction below follows §3.1.4 (Section3: Wingtip generation)
and its code listing, with §§1.1.2, 1.1.4, 3.1.5, 3.1.7 and 4.2 informing the rest.

================================================================================
WHAT THE PAPER STATES
================================================================================

**The inner airfoil (§3.1.4, code line 273: `X = 0.33`).** "The boundaries of the
inner airfoil are generated by taking the difference between the upper and lower
airfoil and either substituting or adding a fraction of this value to the original
point... The result is then multiplied by 1/3 and substituted from the first value.
This results in an inner airfoil that is a third the size of the original airfoil
and follows the shape of the first airfoil very precisely, **even in concave
areas**."

    inner_upper(x) = zu(x) - X * (zu(x) - zl(x))
    inner_lower(x) = zl(x) + X * (zu(x) - zl(x))         X = 0.33

Same convex-combination family COMMON_BRIEF §1 arrived at independently, here at
``width_frac = 1 - 2X = 0.34``. The paper's justification is the one that matters:
it follows the section even where the section is concave.

**The 45-degree rule (§3.1.4).** "The points for the end of the splines are created
so that the connection lines from these to the outer airfoil are **45 degrees**. The
45 degrees are important because they allow for the most regular translation of
cells on each side of the connecting line."

Code lines 403-407 give the two end stations:

    x_te_end   = x(inner aft) - 1/4 * te_thickness          (line 403)
    x_nose_end = sqrt(2) * 0.003 * chord                    (line 407)

The sqrt(2) is the 45-degree factor. Both end regions are therefore **tiny** — about
0.0042 chord at the nose against a 0.005-chord blunt base. That is what lets the
nose domain and the trailing-edge domain carry the same point count without either
being starved, and it is the detail that makes this topology work.

**Eight subsections (§3.1.4).** "To generate a structured mesh it is necessary to
have surfaces with four corners... To achieve that, the first airfoil is
subsectioned into eight parts." From the code (lines 470-527) the outer airfoil
splits at the trailing edge, **mid-chord** on each surface, and the nose transition;
the inner airfoil splits to match. Mid-chord is a real split: it lets the fore and
aft halves carry opposite progressions.

**Progression (§§1.1.2, 3.1.4).** Points follow a geometric series, and "on these
curves, the number of nodes is highest towards the nose and towards the Trailing
Edge to achieve a good resolution of the important parts while simultaneously saving
nodes in the less aerodynamically complicated middle."

**This one is implemented and DEFAULTED OFF (`ratio = 1.0`), measured.** On the
AERIS BWB it degrades the mesh monotonically, and badly:

    ratio 1.00   min scaled Jac  +0.45487   skew 0.699   range  842
    ratio 1.05                   +0.00508   skew 0.997   range 1283
    ratio 1.12                   -0.05444   skew 0.999   range 2118

Clustering toward the ends shrinks the cells at exactly the two places this
geometry is already tightest — a 0.0042-chord nose domain and a 0.005-chord blunt
base — and the long centre domain then has to interpolate across the resulting
mismatch. The paper's blade has a proportionally much thicker trailing edge, so the
same clustering costs it less. Kept as a knob at 1.0 so the finding is
reproducible.

**Cell-size matching (§3.1.4, eq 3.2-3.4).** Node counts on the nose edge and on the
connection lines are computed so the first step of one curve equals the cell size of
its neighbour — "the bordering cells on each side of the lines have the same size".

================================================================================
WHAT THE PAPER DOES NOT DELIVER — decisive for this study
================================================================================

**Openblademesh never achieved a pyHyp extrusion of the whole wing.** §4.1: "This
approach was not available at moment of publication and therefore the extrusion with
Pyhyp was not enabled as a standalone. **While the wingtip on its own can be meshed
with Pyhyp the whole wing can only be meshed by software with different extrusion
methods such as pointwise.**" §3.1.7 gives the reason: "Pyhyp cannot extrude the
whole wing for too big step size differences between the wingtip and the wing."

That is ADR-0010, reached independently by this study and confirmed by its source.

**The spanwise law that would fix it is stated but unimplemented.** §3.1.5 gives
equations 3.5-3.10 for one geometric series spanning the whole wing, then: "the
algebraic solution approach takes too long and the numerical approach is yet to be
finished so the formula is given here **but is not used**." The implemented fallback
is a negative exponential (eq 3.11) the paper itself calls "coarser" and "not
sufficient" on its own NREL 5MW example.

**§4.2.3 supplies the number this study lacked:** cell growth "must not exceed a
factor between 1.3 and 1.6" for stable extrusion, and Openblademesh has "no option
to set a maximum value or a range in the current version."

So S1 inherits a validated *tip* topology and an explicitly unfinished spanwise law.
The tip is implemented faithfully; the growth limit §4.2.3 names but cannot enforce
is enforced here. `STUDY.md` §1 records the split.
"""

