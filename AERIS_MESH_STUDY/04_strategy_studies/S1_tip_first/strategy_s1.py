# §3.1.4 inner airfoil and the 45-degree end stations
# ---------------------------------------------------------------------------


def _surfaces(coords: Array, le_index: int):
    return coords[: le_index + 1][::-1], coords[le_index:]  # LE->upper TE, LE->lower TE


def inner_airfoil(coords: Array, le_index: int, xq: Array, *, dilation: float):
    """Paper §3.1.4 / code lines 294-343: the third-thickness inner airfoil."""
    upper, lower = _surfaces(coords, le_index)
    zu = np.interp(xq, upper[:, 0], upper[:, 1])
    zl = np.interp(xq, lower[:, 0], lower[:, 1])
    t = zu - zl
    return zu - dilation * t, zl + dilation * t


def end_stations(
    coords: Array, le_index: int, *, end_scale: float = 1.0
) -> tuple[float, float]:
    """The two 45-degree end stations, paper code lines 403 and 407.

    **DEVIATION FROM THE PAPER, recorded as one.** ``end_scale`` widens both end
    domains by a common factor. The paper's constants are blade-specific: the nose
    station is ``sqrt(2)*0.003*chord`` (0.42% of chord) and the aft station is
    ``te_thickness/4`` (0.125% of chord here). On the NREL 5MW rotor blade the blunt
    trailing edge is proportionally far thicker, so those domains are a reasonable
    size. On this BWB section they are two to three orders of magnitude finer than
    the mid-chord cells, which is the whole of S1's cell-size range problem —
    measured **754-897** against the 99-140 that has actually marched, and
    min-cell/`s0` of **2.1** where Stage 02's S1 exploded at 0.9.

    ``end_scale = 1.0`` reproduces the paper exactly and stays the reference. The
    default is **5.0**, which is where the cell-size range bottoms out:

        end_scale   min scaled Jac   range   min cell   est min/s0
            1.0        +0.45487      810.0    26.6 um       2.1     EXPLODED
            2.0        +0.46939      421.1    51.1 um       4.0
            3.0        +0.35330      280.6    76.7 um       6.1
            5.0        +0.24199     *172.7*  124.6 um       9.8     <- default
            8.0        +0.14195      200.8   140.6 um      11.1
           12.0        +0.07613      231.8   162.3 um      12.8

    At 1.0 — the paper exactly — the march explodes at layer 2 with a minimum
    volume of -7.33e+62, the same signature Stage 02's S1 produced at min-cell/s0
    of 0.9. The paper predicts this itself in section 3.1.7.
    """
    upper, lower = _surfaces(coords, le_index)
    x_le, x_te = float(upper[0, 0]), float(upper[-1, 0])
    chord = x_te - x_le
    te_abs = float(upper[-1, 1] - lower[-1, 1])
    x_nose = x_le + end_scale * NOSE_END_FRAC * chord
    x_aft = x_te - end_scale * TE_END_TE_FRACTION * te_abs
    if not (x_le < x_nose < x_aft < x_te):
        raise MeshBuildError(
            f"45-degree end stations out of order: le {x_le}, nose {x_nose}, "
            f"aft {x_aft}, te {x_te}"
        )
    return x_nose, x_aft


def _straight(p0: Array, p1: Array, n: int) -> Array:
    s = np.linspace(0.0, 1.0, n)[:, None]
    return (1.0 - s) * p0 + s * p1


def _point_on(curve: Array, x: float) -> Array:
    return np.array([x, float(np.interp(x, curve[:, 0], curve[:, 1]))])


def outer_station_at_45(surface: Array, inner_pt: Array, x_hi: float) -> float:
    """x on ``surface`` where the line to ``inner_pt`` makes 45 degrees.

    Paper §3.1.4: "The points for the end of the splines are created so that the
    connection lines from these to the outer airfoil are 45 degrees. The 45 degrees
    are important because they allow for the most regular translation of cells on
    each side of the connecting line."

    Solving it is what the rule is FOR. Splitting the outer arc at the inner
    point's own x instead makes the connection line vertical — and near the leading
    edge the contour is itself nearly vertical, so the two run collinear and the
    corner cell degenerates. Measured with the naive split: `tip_nose` skewness
    **1.000**, min scaled Jacobian **-0.000**. This is the same ~180-degree corner
    ADR-0006 identified for cap4, arrived at from the opposite direction.

    45 degrees means |dx| == |dz|, so the root of

        f(x) = (x - x_i) - |z(x) - z_i|

    is sought between the inner station and ``x_hi`` by bisection.
    """
    x_i, z_i = float(inner_pt[0]), float(inner_pt[1])

    def f(x: float) -> float:
        return (x - x_i) - abs(float(np.interp(x, surface[:, 0], surface[:, 1])) - z_i)

    lo, hi = x_i + 1e-9, float(x_hi)
    if f(hi) < 0.0:
        return hi
    for _ in range(80):
        mid = 0.5 * (lo + hi)
        if f(mid) > 0.0:
            hi = mid
        else:
            lo = mid
    return 0.5 * (lo + hi)


